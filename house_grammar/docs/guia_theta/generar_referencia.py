def contracts():
    found = {}

    def visit(t):
        if is_dataclass(t) and t.__name__ not in found:
            found[t.__name__] = t
            for value in get_type_hints(t).values():
                visit(value)
        for arg in get_args(t):
            visit(arg)

    visit(ReconstructionRequest)
    return found


